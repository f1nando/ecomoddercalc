export const RULES = Object.freeze({ mass: [1, 100000], crr: [0, 0.5], cd: [0, 3],
  area: [0.01, 50], efficiency: [1, 100], rho: [0.1, 2], g: [9, 10],
  grade: [0, 100], wind: [0, 200], engineEfficiency: [1, 100],
  fuelWh: [1, 100000], auxiliary: [0, 100000] });
export function validate(input) {
  const result = {};
  for (const [key, [min, max]] of Object.entries(RULES)) {
    const value = input[key];
    if (typeof value !== 'number' || !Number.isFinite(value) || value < min || value > max) {
      throw new RangeError(`Недопустимое значение: ${key} (${min}…${max}).`);
    }
    result[key] = value;
  }
  return Object.freeze(result);
}
export function parseSpeeds(text) {
  if (typeof text !== 'string' || text.length > 1000 || !text.trim()) throw new RangeError('Укажите скорости через точку с запятой.');
  const tokens = text.trim().split(/[;\s]+/);
  if (tokens.length > 40) throw new RangeError('Не более 40 скоростей.');
  const speeds = tokens.map(token => {
    if (!/^\d+(?:[.,]\d+)?$/.test(token)) throw new RangeError('Скорости разделяются точкой с запятой; пример: 16; 32; 48.');
    const v = Number(token.replace(',', '.'));
    if (!Number.isFinite(v) || v < 0 || v > 400) throw new RangeError('Скорость должна быть от 0 до 400 км/ч.');
    return v;
  });
  return [...new Set(speeds)].sort((a, b) => a - b);
}
export function calculate(speed, input) {
  if (!Number.isFinite(speed) || speed < 0 || speed > 400) throw new RangeError('Недопустимая скорость.');
  const p = validate(input), v = speed / 3.6, airSpeed = (speed + p.wind) / 3.6;
  const angle = Math.atan(p.grade / 100);
  const rollingForce = p.mass * p.g * p.crr * Math.cos(angle);
  const gradeForce = p.mass * p.g * Math.sin(angle);
  const aeroForce = 0.5 * p.rho * p.cd * p.area * airSpeed ** 2;
  const rollingKW = rollingForce * v / 1000, aeroKW = aeroForce * v / 1000;
  const gradeKW = gradeForce * v / 1000;
  const wheelKW = rollingKW + aeroKW + gradeKW;
  // Auxiliary power is explicitly defined at the engine shaft (not at wheels).
  const engineKW = wheelKW / (p.efficiency / 100) + p.auxiliary / 1000;
  const fuelLitresPerHour = engineKW / (p.engineEfficiency / 100) / (p.fuelWh / 1000) * 3.785411784;
  const litresPer100 = speed > 0 ? fuelLitresPerHour / speed * 100 : null;
  return Object.freeze({ speed, metresPerSecond: v, rollingForce, aeroForce, gradeForce,
    rollingKW, aeroKW, gradeKW, wheelKW, engineKW, horsepower: engineKW / 0.745699872,
    fuelLitresPerHour, litresPer100 });
}
export function csv(rows, { profile, preset, parameters }) {
  const decimal = value => value === null ? '' : String(Number(value.toFixed(6))).replace('.', ',');
  const quote = value => `"${String(value).replaceAll('"', '""')}"`;
  // All text metadata is generated by the app, never arbitrary spreadsheet formulas.
  const metadata = `# EcoModderCalc; ${profile}; ${preset}`;
  const params = Object.entries(parameters).map(([k,v]) => `# ${k}=${decimal(v)}`);
  const header = ['км/ч', 'Кочение Н', 'Воздух Н', 'Подъём Н', 'Колёса кВт', 'Двигатель кВт', 'л/100 км (оценка)'];
  return '\uFEFF' + [metadata, ...params, header.map(quote).join(';'), ...rows.map(r =>
    [r.speed, r.rollingForce, r.aeroForce, r.gradeForce, r.wheelKW, r.engineKW, r.litresPer100].map(decimal).map(quote).join(';'))].join('\r\n');
}
